#!/usr/bin/env node

'use strict'

const fs = require('fs')
const path = require('path')
const zlib = require('zlib')

const artifactRoot = path.resolve(process.argv[2] || 'build/apps/remix-ide')
const packageJson = require(path.resolve('package.json'))
const textExtensions = new Set(['.js', '.css', '.html', '.json'])
const forbiddenPatterns = [
  {
    label: 'Nx task-runner environment',
    pattern: /\bNX_(?:CLI_SET|LOAD_DOT_ENV_FILES|WORKSPACE_ROOT|TERMINAL_OUTPUT_PATH|STREAM_OUTPUT|TASK_TARGET_PROJECT|TASK_HASH)\b/
  },
  {
    label: 'Nx terminal-output path',
    pattern: /node_modules[\\/]\.cache[\\/]nx[\\/]terminalOutputs/
  }
]

// Match this build machine, not every path-shaped string in third-party code.
// Some copied vendor assets contain their upstream authors' historical paths
// (for example /home/yann/Remix/...), which are neither generated by this build
// nor private CI metadata. Scanning the actual workspace/home paths still
// catches webpack/Nx source leakage without turning those fixtures into a
// permanent false-positive release gate.
const buildPathCandidates = new Set([
  process.cwd(),
  process.env.HOME,
  process.env.GITHUB_WORKSPACE,
  process.env.CI_PROJECT_DIR,
  process.env.BUILD_WORKSPACE_DIRECTORY,
  process.env.NX_WORKSPACE_ROOT
].filter((value) => typeof value === 'string' && path.isAbsolute(value)))

try {
  buildPathCandidates.add(fs.realpathSync.native(process.cwd()))
} catch (error) {
  // The lexical cwd remains sufficient if the platform cannot resolve it.
}

const forbiddenBuildPathVariants = [...buildPathCandidates]
  .flatMap((candidate) => {
    const withoutTrailingSeparator = candidate.replace(/[\\/]+$/, '')
    const nativeDirectoryPrefix = withoutTrailingSeparator + path.sep
    const portableDirectoryPrefix = withoutTrailingSeparator.replace(/\\/g, '/') + '/'
    return [
      nativeDirectoryPrefix,
      portableDirectoryPrefix,
      JSON.stringify(nativeDirectoryPrefix).slice(1, -1),
      JSON.stringify(portableDirectoryPrefix).slice(1, -1)
    ]
  })
  .filter((candidate, index, all) => candidate.length >= 4 && all.indexOf(candidate) === index)

function walk (directory) {
  const files = []
  for (const entry of fs.readdirSync(directory, { withFileTypes: true })) {
    const target = path.join(directory, entry.name)
    if (entry.isDirectory()) files.push(...walk(target))
    else files.push(target)
  }
  return files
}

function fail (message) {
  console.error(`Production artifact hygiene check failed: ${message}`)
  process.exitCode = 1
}

function containsAbsoluteBuildPath (source, buildPath) {
  let offset = 0
  while (offset < source.length) {
    const index = source.indexOf(buildPath, offset)
    if (index === -1) return false
    const previous = index > 0 ? source[index - 1] : ''
    const prefix = source.slice(Math.max(0, index - 12), index)
    // `/app/` inside `src/app/` or `./app/` is a relative source path, not
    // the absolute container workspace. Quotes, punctuation, string starts,
    // and file/webpack URL prefixes are valid absolute-path boundaries.
    if (
      index === 0 ||
      !/[A-Za-z0-9._/\\-]/.test(previous) ||
      /(?:file|webpack):\/\/$/i.test(prefix)
    ) return true
    offset = index + buildPath.length
  }
  return false
}

if (!fs.existsSync(artifactRoot)) {
  fail(`artifact directory does not exist: ${artifactRoot}`)
} else {
  const files = walk(artifactRoot)
  const sourceMaps = files.filter((file) => file.endsWith('.map'))
  if (sourceMaps.length) fail(`source maps are present: ${sourceMaps.map((file) => path.relative(artifactRoot, file)).join(', ')}`)

  const versionPath = path.join(artifactRoot, 'assets', 'version.json')
  if (!fs.existsSync(versionPath)) {
    fail('assets/version.json is missing')
  } else {
    const version = JSON.parse(fs.readFileSync(versionPath, 'utf8'))
    if (version.version !== packageJson.version) fail(`version.json reports ${version.version}; expected ${packageJson.version}`)
    if (version.mode !== 'production') fail(`version.json mode is ${version.mode}; expected production`)
  }

  // main.js is the render-blocking cold-start payload. Production v2.3.2
  // shipped an 11.14 MB gzip bundle because solc/soljson was embedded even
  // though the compiler is already served as an on-demand asset. Vendor AI
  // SDKs, unused highlight languages, and the Ant Design barrel were then
  // removed from the entry path, so keep modest headroom above that leaner
  // baseline while preventing either class of regression.
  const mainBundlePath = path.join(artifactRoot, 'main.js')
  if (fs.existsSync(mainBundlePath)) {
    const configuredBudget = Number(process.env.TRONIDE_MAIN_GZIP_BUDGET_BYTES || 4200000)
    if (!Number.isFinite(configuredBudget) || configuredBudget <= 0) {
      fail(`invalid TRONIDE_MAIN_GZIP_BUDGET_BYTES: ${process.env.TRONIDE_MAIN_GZIP_BUDGET_BYTES}`)
    } else {
      const gzipBytes = zlib.gzipSync(fs.readFileSync(mainBundlePath), { level: 9 }).byteLength
      if (gzipBytes > configuredBudget) {
        fail(`main.js gzip size ${gzipBytes} bytes exceeds the ${configuredBudget}-byte cold-start budget`)
      } else {
        console.log(`Production main.js gzip size: ${gzipBytes} bytes (budget ${configuredBudget})`)
      }
    }
  }

  for (const file of files) {
    if (!textExtensions.has(path.extname(file))) continue
    const source = fs.readFileSync(file, 'utf8')
    for (const rule of forbiddenPatterns) {
      const match = source.match(rule.pattern)
      if (match) {
        fail(`${rule.label} found in ${path.relative(artifactRoot, file)} (${JSON.stringify(match[0])})`)
      }
    }
    for (const buildPath of forbiddenBuildPathVariants) {
      if (containsAbsoluteBuildPath(source, buildPath)) {
        fail(`current build-machine path found in ${path.relative(artifactRoot, file)} (${JSON.stringify(buildPath)})`)
        break
      }
    }
  }
}

if (!process.exitCode) {
  console.log(`Production artifact hygiene check passed: ${artifactRoot}`)
}
